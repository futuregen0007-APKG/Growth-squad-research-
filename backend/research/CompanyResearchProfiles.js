/**
 * Returns or dynamically constructs a CompanyResearchProfile for any stock symbol.
 */
export function getCompanyResearchProfile(symbol, fallbackName = '', fallbackSector = 'Generic') {
  const normalized = String(symbol || '').toUpperCase().trim();
  if (COMPANY_RESEARCH_PROFILES[normalized]) {
    return {
      ...COMPANY_RESEARCH_PROFILES[normalized],
      sectorMetrics: SECTOR_METRICS[COMPANY_RESEARCH_PROFILES[normalized].sector] || SECTOR_METRICS.Generic
    };
  }

  const name = fallbackName || normalized;
  const cleanName = name.replace(/\s+(Limited|Ltd\.?|Corporation|Corp\.?)$/i, '');
  const sector = fallbackSector || 'Generic';

  return {
    symbol: normalized,
    companyName: name,
    aliases: [name, cleanName, normalized],
    sector,
    sectorMetrics: SECTOR_METRICS[sector] || SECTOR_METRICS.Generic,
    exchangeSymbols: {
      NSE: normalized,
      BSE: normalized
    },
    investorRelationsUrls: [
      `https://www.${cleanName.toLowerCase().replace(/[^a-z0-9]/g, '')}.com/investors`,
      `https://investor.${cleanName.toLowerCase().replace(/[^a-z0-9]/g, '')}.com`
    ],
    annualReportUrls: [],
    commonManagementTerms: [
      'management guidance',
      'revenue guidance',
      'revenue target',
      'EBITDA guidance',
      'margin guidance',
      'order book',
      'order intake',
      'capex',
      'expects',
      'targets',
      'aims'
    ]
  };
}

